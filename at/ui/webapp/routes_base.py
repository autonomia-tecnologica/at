"""The base the route mixins stand on, for the TYPE CHECKER and for nobody else.

The mixins (`AiRoutes`, `GetRoutes`, ...) were cut out of the `Handler` without a
change of behaviour, and they still call each other and the request machinery
(`_json`, `_may`, `_body`, `wfile`, `server`...) through `self`. At run time that
works because the `Handler` inherits all of them; for `mypy` each mixin alone has
none of it. `RouteBase` is a `BaseHTTPRequestHandler` (so `wfile`, `headers`,
`send_response`... are typed) and, under `TYPE_CHECKING` ONLY, declares the
members the siblings supply. Nothing declared there exists at run time, so it
shadows no real method in the MRO.
"""

from __future__ import annotations

from http.server import BaseHTTPRequestHandler
from pathlib import Path
from typing import TYPE_CHECKING, Callable

if TYPE_CHECKING:
    from at.ui.webapp import session
    from at.ui.webapp.serve import Server


class RouteBase(BaseHTTPRequestHandler):
    if TYPE_CHECKING:
        server: Server  # type: ignore[assignment]
        _held: object
        _local_cookie: str | None

        # The Handler's own.
        def _not_found(self) -> None: ...
        def _declarable_payload(self) -> list[dict]: ...
        def _local(self) -> bool: ...

        # GateRoutes.
        def _in(self) -> session.Session | None: ...
        def _gate(self) -> bool: ...
        def _may(
            self, permission: str, *, owing: Callable[[], None] | None = None
        ) -> bool: ...
        def _legal(self, permission: str) -> bool: ...
        def _actor(self) -> dict | None: ...

        # SendRoutes.
        def _send(self, status: int, body: bytes, ctype: str, extra: dict | None = None) -> None: ...
        def _text(self, text: str, ctype: str = ..., status: int = 200,
                  extra: dict | None = None) -> None: ...
        def _json(self, payload: object, status: int = 200,
                  extra: dict | None = None) -> None: ...
        def _file(self, path: Path, hosted_version: str | None = None,
                  extra: dict | None = None) -> None: ...
        def _body(self) -> dict | None: ...

        # TableRoutes.
        def _crud_actions(self, table: str) -> list[str]: ...
        def _table_actions(self, table: str) -> list[str]: ...
        def _project_actions(self) -> list[str]: ...

        # The GET handlers, dispatched across mixins.
        def _get_file(self, path: str) -> None: ...
        def _get_file_bytes(self, path: str) -> None: ...
        def _get_strongbox_download(self, token: str) -> None: ...
        def _get_events(self) -> None: ...
